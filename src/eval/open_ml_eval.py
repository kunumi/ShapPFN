import numpy as np
import pandas as pd
import torch
from sklearn.tree import DecisionTreeClassifier
from sklearn.neighbors import KNeighborsClassifier
from sklearn.ensemble import RandomForestClassifier
from tabpfn import TabPFNClassifier
from tabpfn.config import ModelInterfaceConfig, PreprocessorConfig
from pathlib import Path
import argparse

from eval.eval_utils import get_openml_datasets, eval_model
from models import ShapPFNModel, ShapPFNMultiClass, NanoTabPFNModel, NanoTabPFNMultiClass


def main(out_dir, shappfn_path, nanotabpfn_path):
    DATASETS = get_openml_datasets(max_features_eval=100, new_instances_eval=200, target_classes_filter=10)
    NUM_SEEDS = 1

    no_preprocessing_inference_config = ModelInterfaceConfig(
        FINGERPRINT_FEATURE=False,
        PREPROCESS_TRANSFORMS=[PreprocessorConfig(name='none')]
    )


    def apply_aggregation(eval_results: dict, func=np.mean):
        aggregated_result = {}
        for result in eval_results:
            for metric, value in result.items():
                if metric not in aggregated_result:
                    aggregated_result[metric] = []
                aggregated_result[metric].append(value)
        for metric in aggregated_result:
            aggregated_result[metric] = func(aggregated_result[metric])
        return aggregated_result

    shappfn = ShapPFNModel(
        embedding_size=96,
        num_attention_heads=4,
        mlp_hidden_size=192,
        num_layers=3,
        num_outputs=2,
    )
    shappfn.load_state_dict(torch.load(shappfn_path, map_location="cpu"))
    shappfn.eval()

    nanotabpfn = NanoTabPFNModel(
        embedding_size=96,
        num_attention_heads=4,
        mlp_hidden_size=192,
        num_layers=3,
        num_outputs=2,
    )
    nanotabpfn.load_state_dict(torch.load(nanotabpfn_path, map_location="cpu"))
    nanotabpfn.eval()

    baseline_models = {
        "NanoTabPFN": [NanoTabPFNMultiClass(nanotabpfn, device=torch.device("cuda")) for i in range(NUM_SEEDS)],
        "ShapPFN": [ShapPFNMultiClass(shappfn, device=torch.device("cuda")) for i in range(NUM_SEEDS)],
        "TabPFN v2": [TabPFNClassifier(random_state=i) for i in range(NUM_SEEDS)],
        "TabPFN v2 (no preprocessing)": [TabPFNClassifier(inference_config=no_preprocessing_inference_config, n_estimators=1, random_state=i) for i in range(NUM_SEEDS)],
        "Random Forest": [RandomForestClassifier(random_state=i) for i in range(NUM_SEEDS)],
        "K-Nearest Neighbors": [KNeighborsClassifier()],
        "Decision Tree": [DecisionTreeClassifier(random_state=i) for i in range(NUM_SEEDS)],
    }

    baseline_models_eval = {name: [eval_model(model, datasets=DATASETS) for model in models] for name, models in baseline_models.items()}


    baselines = pd.DataFrame({
        name: apply_aggregation(models, np.mean) for name, models in baseline_models_eval.items()
    }).T

    baselines.to_csv(f"{out_dir}/eval_performance.csv")


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description="Script to score the shap values generated by the model")
    parser.add_argument("--out-dir", type=str, help="The output dir")
    parser.add_argument("--shappfn-path", type=str, help="The shappfn model path")
    parser.add_argument("--nanotabpfn-path", type=str, help="The nanotabpfn model path")

    
    args = parser.parse_args()
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)


    main(out_dir, args.shappfn_path, args.nanotabpfn_path)
